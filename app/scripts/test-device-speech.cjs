const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/services/deviceSpeech.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exported = {};
let options;
let stopCalls = 0;
const speech = { speak: (text, config) => { assert.equal(text, 'Pregunta'); options = config; }, stop: async () => { stopCalls++; } };
vm.runInNewContext(compiled, { exports: exported, require: () => speech, setTimeout, clearTimeout, Error });
(async () => {
  const playing = exported.speakOnDevice('Pregunta');
  let done = false;
  playing.finished.then(() => { done = true; });
  await Promise.resolve();
  assert.equal(done, false, 'Recording must wait until speech finishes');
  assert.equal(options.language, 'es-ES');
  options.onDone();
  await playing.finished;
  assert.equal(done, true);
  const cancelled = exported.speakOnDevice('Pregunta');
  const rejected = assert.rejects(cancelled.finished, /cancelada/);
  cancelled.cancel();
  await rejected;
  assert.equal(stopCalls, 1);
  const failed = exported.speakOnDevice('Pregunta');
  const error = assert.rejects(failed.finished, /No se pudo leer/);
  options.onError();
  await error;
  console.log('Voz del dispositivo: espera al final, idioma, cancelación y error verificados.');
})().catch(error => { console.error(error); process.exitCode = 1; });
