import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['scripts/strands-entry.tsx'], bundle: true, minify: true,
  write: false, platform: 'browser', format: 'iife', jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const javascript = result.outputFiles[0].text.replaceAll('</script', '<\\/script');
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1"/><style>html,body,#root{margin:0;width:100%;height:100%;background:transparent;overflow:hidden}</style></head><body><div id="root"></div><script>if(!document.createElement('canvas').getContext('webgl2'))window.ReactNativeWebView.postMessage('webgl-unavailable');</script><script>${javascript}</script></body></html>`;
await writeFile('src/generated/strandsHtml.ts', `// Generated by pnpm build:strands; do not edit.\nexport const strandsHtml = ${JSON.stringify(html)};\n`);
